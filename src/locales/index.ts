export type Copy = typeof pt;
export type ErrorCode = keyof Copy['errors'];
export function errorCode(error: unknown, fallback: ErrorCode): ErrorCode {
  if (error instanceof DOMException && error.name === 'QuotaExceededError') return '4001';
  if (error instanceof Error && Object.hasOwn(pt.errors, error.message)) return error.message as ErrorCode;
  return fallback;
}
